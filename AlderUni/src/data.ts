export function categoryCount(id: Category) {
  return products.filter((p) => p.category === id).length;
}

export function pesos(n: number) {
  return `₱${n.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
}

export function lineLabel(product: Product, size?: string) {
  if (size) return `${product.name} · ${size}`;
  if (product.variantLabel) return `${product.name} · ${product.variantLabel}`;
  return product.name;
}
